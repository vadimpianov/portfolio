/**
 * Типографика для всех строк интерфейса (вызывается в `useTranslations`):
 * — короткие предлоги, союзы и частицы не висят в конце строки: пробел после них → неразрывный,
 *   слово переносится вместе со следующим («и многое», «в формировании», «of the»);
 * — тире не начинает строку: пробел перед «—» / «–» → неразрывный.
 */
const NBSP = ' ';

// Все слова из 1–2 букв привязываются всегда; из 3 — только служебные.
const SHORT_WORDS = new Set([
  // русские
  'для',
  'без',
  'над',
  'под',
  'при',
  'про',
  'или',
  'что',
  'как',
  'чем',
  'где',
  'это',
  // английские
  'the',
  'and',
  'for',
  'but',
  'nor',
  'its',
  'our',
  'via',
]);

// Аббревиатуры из двух заглавных (UI, ИИ, UX) — не предлоги: их не привязываем, иначе цепочка
// «UI и разная» становится одним неразрывным куском и уезжает на новую строку раньше времени.
const isAbbr = (word: string) =>
  word.length === 2 && word === word.toUpperCase() && word !== word.toLowerCase();

export function typograph(text: string): string {
  return text
    .replace(/ +(?=[—–])/g, NBSP)
    .replace(/(?<=^|[\s («"„“‘*])(\p{L}+) +/gu, (match, word: string) =>
      (word.length <= 2 && !isAbbr(word)) || SHORT_WORDS.has(word.toLowerCase()) ? word + NBSP : match,
    );
}
